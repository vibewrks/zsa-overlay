import Foundation

/// How a physical key behaves on one layer.
nonisolated public enum BindingKind: String, Codable, Sendable {
    /// At least one real action (`tap`, `hold`, `doubleTap` or `tapHold`).
    case mapped
    /// Explicitly switched off on this layer (`KC_NO`); it blocks lower layers.
    case disabled
    /// No action on this layer; it inherits from a layer the caller may not know about.
    case transparent
}

/// The normalized legend for one key on one layer, produced by
/// `scripts/import-keymapp.py` from the Keymapp/Oryx revision JSON.
nonisolated public struct KeyBinding: Codable, Sendable, Hashable {
    public var kind: BindingKind
    /// Primary legend: the layout's custom label when it sets one, else the tap
    /// action's label; `""` when absent (e.g. a hold-only key).
    public var tap: String
    /// Secondary legend: the hold action's label; `""` when absent.
    public var hold: String
    /// Remaining legends: `doubleTap` / `tapHold` labels joined with `" / "`.
    public var extra: String
    /// Key glow colour (`#RRGGBB`) when the layout sets one.
    public var color: String?

    public init(kind: BindingKind, tap: String = "", hold: String = "", extra: String = "", color: String? = nil) {
        self.kind = kind
        self.tap = tap
        self.hold = hold
        self.extra = extra
        self.color = color
    }
}

/// One of the 72 physical keys of the Moonlander Mark I, in Oryx position order.
nonisolated public struct PhysicalKey: Codable, Sendable, Hashable {
    /// Oryx position, 0...71; 0 is the left half's top-left key, 32/68 are the 2u
    /// thumb keys, 57...71 end the right half.
    public var id: Int
    /// Key-unit coordinates (1 unit = one 1u keycap). The board spans 17 x 7 units;
    /// x/y come straight from the QMK Moonlander `LAYOUT` geometry.
    public var x: Double
    public var y: Double
    public var width: Double
    public var height: Double
    /// Degrees; every Moonlander keycap is unrotated, so this is 0.
    public var rotation: Double

    public init(id: Int, x: Double, y: Double, width: Double = 1, height: Double = 1, rotation: Double = 0) {
        self.id = id
        self.x = x
        self.y = y
        self.width = width
        self.height = height
        self.rotation = rotation
    }
}

/// One layer of the keymap. `bindings` is aligned with `Keymap.keys`: the binding at
/// index `i` belongs to the physical key whose `id` is `i`.
nonisolated public struct Layer: Codable, Sendable, Hashable {
    public var index: Int
    public var title: String
    public var bindings: [KeyBinding]

    public init(index: Int, title: String, bindings: [KeyBinding]) {
        self.index = index
        self.title = title
        self.bindings = bindings
    }
}

/// Why a keymap failed to load or validate.
nonisolated public enum KeymapError: Error, Equatable, Sendable {
    /// Keymap.bundled() could not find `keymap.json` in this module's resource bundle.
    case missingBundledResource
    /// The Moonlander has exactly 72 keys.
    case unsupportedKeyCount(expected: Int, actual: Int)
    /// The same physical key id appears twice.
    case duplicateKeyID(Int)
    /// A physical key id outside `0..<keys.count`.
    case keyIDOutOfRange(Int)
    /// `keys[i].id != i`, so bindings could not line up with physical keys.
    case misalignedKeyID(index: Int, id: Int)
    /// A geometry value that is NaN or infinite (`field` is "x", "y", "width", "height" or "rotation").
    case nonFiniteGeometry(keyID: Int, field: String)
    /// A width or height that is zero or negative.
    case nonPositiveDimension(keyID: Int, field: String)
    /// The same layer index appears twice.
    case duplicateLayerIndex(Int)
    /// A layer whose bindings do not cover every physical key.
    case bindingCountMismatch(layer: Int, expected: Int, actual: Int)
}

/// A Moonlander Mark I keymap: geometry for all 72 physical keys plus every configured layer.
nonisolated public struct Keymap: Codable, Sendable {
    /// Oryx layout title, e.g. "learning dvorak".
    public var title: String
    /// Oryx revision hash the data was imported from, e.g. "rba3al".
    public var revision: String
    /// All 72 physical keys, ordered by id.
    public var keys: [PhysicalKey]
    /// Layers ordered by `index`.
    public var layers: [Layer]

    /// The Moonlander Mark I has 72 keys; a keymap must cover exactly those.
    public static let moonlanderKeyCount = 72

    public init(title: String, revision: String, keys: [PhysicalKey], layers: [Layer]) {
        self.title = title
        self.revision = revision
        self.keys = keys
        self.layers = layers
    }

    /// Loads the keymap bundled with this module (the resource generated by
    /// `scripts/import-keymapp.py`).
    public static func bundled() throws -> Keymap {
        guard let url = Bundle.module.url(forResource: "keymap", withExtension: "json") else {
            throw KeymapError.missingBundledResource
        }
        return try load(url: url)
    }

    /// Decodes and validates a keymap JSON file.
    public static func load(url: URL) throws -> Keymap {
        let data = try Data(contentsOf: url)
        let keymap = try JSONDecoder().decode(Keymap.self, from: data)
        try keymap.validate()
        return keymap
    }

    /// Checks the invariants the overlay relies on: 72 keys with ids `0...71` in order,
    /// finite non-degenerate geometry, unique layer indices, and one binding per key per layer.
    public func validate() throws {
        guard keys.count == Keymap.moonlanderKeyCount else {
            throw KeymapError.unsupportedKeyCount(expected: Keymap.moonlanderKeyCount, actual: keys.count)
        }
        var seenIDs = Set<Int>()
        for key in keys {
            guard seenIDs.insert(key.id).inserted else {
                throw KeymapError.duplicateKeyID(key.id)
            }
            guard keys.indices.contains(key.id) else {
                throw KeymapError.keyIDOutOfRange(key.id)
            }
        }
        for (index, key) in keys.enumerated() where key.id != index {
            throw KeymapError.misalignedKeyID(index: index, id: key.id)
        }
        for key in keys {
            try Keymap.validateGeometry(key)
        }
        var seenLayerIndices = Set<Int>()
        for layer in layers {
            guard seenLayerIndices.insert(layer.index).inserted else {
                throw KeymapError.duplicateLayerIndex(layer.index)
            }
            guard layer.bindings.count == keys.count else {
                throw KeymapError.bindingCountMismatch(layer: layer.index, expected: keys.count, actual: layer.bindings.count)
            }
        }
    }

    /// The binding for physical key `id` from the caller-supplied layer stack.
    ///
    /// `activeLayers` is ordered bottom to top, so the last entry has the highest
    /// precedence. The topmost supplied layer that provides a binding for `id` wins and
    /// its binding is returned verbatim: a `.transparent` binding stays `.transparent`
    /// instead of falling through to a lower layer, because only the caller knows which
    /// layers are really active (the sidecar reports a single current layer). Render
    /// `.transparent` as the inherit marker, or pass that layer's index on its own to
    /// display the layer in full.
    ///
    /// Returns `nil` when no supplied layer provides a binding for `id`.
    public func resolvedBinding(at id: Int, activeLayers: [Int]) -> KeyBinding? {
        for layerIndex in activeLayers.reversed() {
            guard let layer = layers.first(where: { $0.index == layerIndex }),
                  layer.bindings.indices.contains(id) else {
                continue
            }
            return layer.bindings[id]
        }
        return nil
    }

    private static func validateGeometry(_ key: PhysicalKey) throws {
        for (field, value) in [("x", key.x), ("y", key.y), ("width", key.width), ("height", key.height), ("rotation", key.rotation)] {
            guard value.isFinite else {
                throw KeymapError.nonFiniteGeometry(keyID: key.id, field: field)
            }
        }
        guard key.width > 0 else {
            throw KeymapError.nonPositiveDimension(keyID: key.id, field: "width")
        }
        guard key.height > 0 else {
            throw KeymapError.nonPositiveDimension(keyID: key.id, field: "height")
        }
    }
}
